#!/usr/bin/env bash
#
# Regenerates src/profile_photo.hpp from images/profile.jpg.
#
# Run this only when the photo changes — the generated header is committed, so a
# plugin build needs neither Python nor an image decoder.
#
#   ./tools/generate_profile_photo.sh
#
# Requirements: python3 (a venv with Pillow is created under build/ automatically).

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK_DIR="$REPO_ROOT/build/photo"
SOURCE="$REPO_ROOT/images/profile.jpg"
HEADER="$REPO_ROOT/src/profile_photo.hpp"

# Shown at roughly 130 px; 240 px stays sharp on a Retina display at UI scale 1.0
# without bloating every plugin binary. A multiple of 4 keeps each RGB row 4-byte
# aligned, which is what glTexImage2D expects by default.
SIZE=240

mkdir -p "$WORK_DIR"
[ -x "$WORK_DIR/venv/bin/python" ] || { python3 -m venv "$WORK_DIR/venv"; "$WORK_DIR/venv/bin/pip" install -q Pillow; }

"$WORK_DIR/venv/bin/python" -I - "$SOURCE" "$HEADER" "$SIZE" <<'PY'
import sys
from PIL import Image, ImageOps

source, header, size = sys.argv[1], sys.argv[2], int(sys.argv[3])

image = ImageOps.fit(Image.open(source).convert("RGB"), (size, size), Image.LANCZOS)
pixels = image.tobytes()

lines = []
for offset in range(0, len(pixels), 24):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in pixels[offset:offset + 24]) + ",")

with open(header, "w", encoding="utf-8") as out:
    out.write("// Generated by tools/generate_profile_photo.sh — do not edit by hand.\n")
    out.write("//\n")
    out.write("// Profile photo of Robert Wellinger. All rights reserved; not covered by the MIT\n")
    out.write("// license of the source code. See LICENSE.\n")
    out.write("#pragma once\n\n")
    out.write("namespace WellysAbout::ProfilePhoto\n{\n\n")
    out.write(f"inline constexpr int width  = {size};\n")
    out.write(f"inline constexpr int height = {size};\n\n")
    out.write("// Tightly packed RGB, top row first.\n")
    out.write("inline constexpr unsigned char rgb[] = {\n")
    out.write("\n".join(lines))
    out.write("\n};\n\n} // namespace WellysAbout::ProfilePhoto\n")

print(f"  {header} — {size}x{size} RGB, {len(pixels)} bytes of pixel data")
PY
